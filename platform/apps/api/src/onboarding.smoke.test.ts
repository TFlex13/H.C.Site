import test from 'node:test';
import assert from 'node:assert/strict';
import { createApp } from './app.js';
import { createHash } from 'node:crypto';

// Route registration catches duplicate Fastify routes before the server starts.
test('onboarding routes register and draft agreement downloads without a database', async () => {
  const app = await createApp(null);
  try {
    await app.ready();
    const dashboard=await app.inject({method:'GET',url:'/admin/dashboard'});
    assert.equal(dashboard.statusCode,200);
    assert.match(dashboard.body,/Agreement version register/);
    assert.match(dashboard.body,/agreementVersionDirectory/);
    assert.match(dashboard.body,/id="repSearch"/);
    assert.match(dashboard.body,/id="agreementSearch"/);
    assert.match(dashboard.body,/id="onboardingSearch"/);
    assert.match(dashboard.body,/id="storeReviewSearch"/);
    assert.match(dashboard.body,/id="storeReviewDirectory"/);
    assert.match(dashboard.body,/Their store portfolio will be created automatically/);
    assert.doesNotMatch(dashboard.body,/id="storeReviewTerritory"/);
    assert.match(dashboard.body,/id="storeReviewDetail"/);
    assert.match(dashboard.body,/function storeReviewRenderQueue/);
    assert.match(dashboard.body,/storeReviewDocDecision/);
    assert.doesNotMatch(dashboard.body,/Open store onboarding review queue/);
    assert.match(dashboard.body,/function filterAgreementVersions/);
    assert.match(dashboard.body,/View PDF/);
    assert.match(dashboard.body,/Download PDF/);
    assert.match(dashboard.body,/agreementPdfViewer/);
    assert.match(dashboard.body,/fetchAgreementPdf/);
    assert.match(dashboard.body,/function filterOnboardingQueue/);
    assert.match(dashboard.body,/function filterRepresentatives/);
    assert.match(dashboard.body,/No representatives match your search/);
    assert.match(dashboard.body,/representativeProfileView/);
    assert.match(dashboard.body,/openRepresentativeProfile/);
    assert.match(dashboard.body,/id="profileReviewDocuments"/);
    assert.match(dashboard.body,/rep-profile-toolbar/);
    assert.match(dashboard.body,/rep-profile-identity/);
    assert.match(dashboard.body,/Back to directory/);
    assert.match(dashboard.body,/id="reviewBackToProfile"/);
    assert.match(dashboard.body,/id="documentViewStatus"/);
    assert.match(dashboard.body,/document-status-error/);
    assert.match(dashboard.body,/Could not open/);
    assert.match(dashboard.body,/openProfileOnboardingReview/);
    const deepLink=await app.inject({method:'GET',url:'/admin/dashboard/representatives/00000000-0000-0000-0000-000000000000'});
    assert.equal(deepLink.statusCode,200);
    const repProfile=await app.inject({method:'GET',url:'/admin/representatives/00000000-0000-0000-0000-000000000000/overview'});
    assert.equal(repProfile.statusCode,403);
    const directReview=await app.inject({method:'GET',url:'/admin/representative-onboarding/00000000-0000-0000-0000-000000000000'});
    assert.equal(directReview.statusCode,403);
    const agreementPdf=await app.inject({method:'GET',url:'/admin/contractor-agreement/versions/00000000-0000-0000-0000-000000000000/pdf'});
    assert.equal(agreementPdf.statusCode,403);
    const agreementPdfDownload=await app.inject({method:'GET',url:'/admin/contractor-agreement/versions/00000000-0000-0000-0000-000000000000/pdf?download=1'});
    assert.equal(agreementPdfDownload.statusCode,403);
    const page = await app.inject({method:'GET',url:'/representative/onboarding/profile'});
    assert.equal(page.statusCode,200);
    assert.match(String(page.headers['content-type']||''),/text\/html/);
    assert.match(page.body,/Upload agreement PDF/);
    assert.match(page.body,/Submit for review/);
    const repDashboard=await app.inject({method:'GET',url:'/representative/dashboard'});
    assert.equal(repDashboard.statusCode,200);
    assert.match(repDashboard.body,/Generate registration link/);
    assert.match(repDashboard.body,/territoryMap/);
    assert.match(repDashboard.body,/tile.openstreetmap.org/);
    const unauthorizedLocate=await app.inject({method:'POST',url:'/representative/stores/00000000-0000-0000-0000-000000000000/locate'});
    assert.equal(unauthorizedLocate.statusCode,403);
    const storeIntake=await app.inject({method:'GET',url:'/store/onboarding'});
    assert.match(storeIntake.body,/Create password \(minimum 12 characters\)/);
    assert.match(storeIntake.body,/id="storePasswordConfirm"/);
    assert.equal(storeIntake.statusCode,200);
    assert.match(storeIntake.body,/Register your store/);
    assert.match(storeIntake.body,/License expiration date/);
    const adminStorePage=await app.inject({method:'GET',url:'/admin/store-onboarding/dashboard'});
    assert.equal(adminStorePage.statusCode,200);
    assert.match(adminStorePage.body,/Store application review/);
    const unauthorizedInvites=await app.inject({method:'GET',url:'/representative/store-invitations'});
    assert.equal(unauthorizedInvites.statusCode,403);
    const unauthorizedQueue=await app.inject({method:'GET',url:'/admin/store-onboarding'});
    assert.equal(unauthorizedQueue.statusCode,403);
    const invalidInvite=await app.inject({method:'POST',url:'/store/onboarding/details',payload:{token:'invalid'}});
    assert.equal(invalidInvite.statusCode,404);
    const vendorPage=await app.inject({method:'GET',url:'/vendor/dashboard'});
    assert.equal(vendorPage.statusCode,200);
    assert.match(vendorPage.body,/Vendor sign in/);
    assert.match(vendorPage.body,/Add a product/);
    const vendorSignup=await app.inject({method:'GET',url:'/vendor/signup'});
    assert.equal(vendorSignup.statusCode,200);
    assert.match(vendorSignup.body,/Create your vendor login/);
    assert.match(dashboard.body,/id="vendorInviteForm"/);
    assert.match(dashboard.body,/id="vendorOfferRows"/);
    assert.match(dashboard.body,/id="vendorCatalogDirectory"/);
    assert.match(page.body,/Sales catalog/);
    const vendorAccess=await app.inject({method:'GET',url:'/vendor/overview'});
    assert.equal(vendorAccess.statusCode,403);
    const vendorCatalog=await app.inject({method:'GET',url:'/representative/catalog'});
    assert.equal(vendorCatalog.statusCode,403);
    const privateOffers=await app.inject({method:'GET',url:'/admin/vendor-catalog/offers'});
    assert.equal(privateOffers.statusCode,403);
    const privateInvite=await app.inject({method:'POST',url:'/admin/vendors/00000000-0000-0000-0000-000000000000/invitations',payload:{email:'vendor@example.com'}});
    assert.equal(privateInvite.statusCode,403);
    const storePortal=await app.inject({method:'GET',url:'/store/dashboard'});
    assert.equal(storePortal.statusCode,200);
    assert.match(storePortal.body,/Approved catalog/);
    const storeAccountSetup=await app.inject({method:'GET',url:'/store/account'});
    assert.equal(storeAccountSetup.statusCode,200);
    assert.match(storeAccountSetup.body,/Activate your store login/);
    assert.match(page.body,/Place an order request for a store/);
    assert.match(dashboard.body,/id="storeAccountInviteForm"/);
    assert.match(dashboard.body,/id="storeOrderRequestRows"/);
    const unauthorizedStore=await app.inject({method:'GET',url:'/store/catalog'});
    assert.equal(unauthorizedStore.statusCode,403);
    const unauthorizedOrderable=await app.inject({method:'GET',url:'/representative/catalog/orderable'});
    assert.equal(unauthorizedOrderable.statusCode,403);
    const unauthorizedOrders=await app.inject({method:'POST',url:'/catalog/order-requests',payload:{storeId:'00000000-0000-0000-0000-000000000000',items:[{productId:'00000000-0000-0000-0000-000000000000',quantity:1}]}});
    assert.equal(unauthorizedOrders.statusCode,403);
    const unauthorizedInvite=await app.inject({method:'POST',url:'/admin/stores/00000000-0000-0000-0000-000000000000/account-invitations',payload:{email:'owner@example.com'}});
    assert.equal(unauthorizedInvite.statusCode,403);
    const pdf=await app.inject({method:'GET',url:'/representative/contractor-agreement/draft.pdf'});
    assert.equal(pdf.statusCode,200);
    assert.match(String(pdf.headers['content-type']||''),/application\/pdf/);
    assert.equal(pdf.rawPayload.subarray(0,5).toString(),'%PDF-');
    assert.equal(pdf.headers['x-agreement-version'],'1.0-draft');
    assert.equal(pdf.headers['x-document-sha256'],createHash('sha256').update(pdf.rawPayload).digest('hex'));
    const version=await app.inject({method:'GET',url:'/representative/contractor-agreement/version'});
    assert.equal(version.statusCode,403);
    const sign=await app.inject({method:'POST',url:'/representative/contractor-agreement/sign'});
    assert.equal(sign.statusCode,403);
    const unauthorized=await app.inject({method:'GET',url:'/admin/representative-onboarding/00000000-0000-0000-0000-000000000000/documents'});
    assert.equal(unauthorized.statusCode,403);
  } finally {
    await app.close();
  }
});
